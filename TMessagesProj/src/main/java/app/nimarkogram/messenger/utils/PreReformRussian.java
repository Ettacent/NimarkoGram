    public static Result convert(String text, ArrayList<TLRPC.MessageEntity> entities) {
        Result res = new Result();
        res.entities = entities;
        if (text == null || text.isEmpty()) { res.text = text; return res; }
        final int n = text.length();

        boolean[] prot = new boolean[n];
        if (entities != null) {
            for (int k = 0; k < entities.size(); k++) {
                TLRPC.MessageEntity e = entities.get(k);
                if (e == null || !isProtected(e)) continue;
                int s = Math.max(0, e.offset);
                int en = Math.min(n, e.offset + e.length);
                for (int i = s; i < en; i++) prot[i] = true;
            }
        }

        StringBuilder out = new StringBuilder(n + (n >> 3) + 8);
        int[] map = new int[n + 1];
        int i = 0;
        boolean prepPending = false; 
        while (i < n) {
            char c = text.charAt(i);
            if (isCyrillicLetter(c) && !prot[i]) {
                int j = i;
                while (j < n && isCyrillicLetter(text.charAt(j)) && !prot[j]) j++;
                String orig = text.substring(i, j);
                String lower = orig.toLowerCase(Locale.ROOT);
                String conv;
                try { conv = convertWord(orig); }
                catch (Throwable t) { conv = orig; }
                
                if (prepPending) {
                    if (isSkippableAdjective(lower)) {
                        
                    } else {
                        conv = applyPrepEnding(conv, lower);
                        prepPending = false;
                    }
                }
                if (PREP_WORDS.contains(lower)) prepPending = true;
                appendWord(out, map, i, j, orig, conv);
                i = j;
            } else {
                if (!Character.isWhitespace(c)) prepPending = false; 
                map[i] = out.length();
                out.append(c);
                i++;
            }
        }
        map[n] = out.length();
        res.text = out.toString();
        res.entities = remapEntities(entities, map, n);
        return res;
    }

    private static void appendWord(StringBuilder out, int[] map, int start, int end, String original, String conv) {
        int outStart = out.length();
        int wordLen = end - start;
        out.append(conv);
        
        int[] local = alignBoundaries(original, conv);
        for (int t = 0; t < wordLen; t++) map[start + t] = outStart + local[Math.min(t, local.length - 1)];
    }

    private static int[] alignBoundaries(String source, String target) {
        int n = source.length(), m = target.length();
        
        if ((long) n * m > 65_536L) {
            int[] boundary = new int[n + 1];
            int prefix = 0;
            while (prefix < n && prefix < m
                    && Character.toLowerCase(source.charAt(prefix)) == Character.toLowerCase(target.charAt(prefix))) {
                boundary[prefix] = prefix;
                prefix++;
            }
            for (int i = prefix; i <= n; i++) {
                boundary[i] = prefix + (int) (((long) (i - prefix) * (m - prefix)) / Math.max(1, n - prefix));
            }
            boundary[n] = m;
            return boundary;
        }
        int[][] dp = new int[n + 1][m + 1];
        for (int i = 0; i <= n; i++) dp[i][0] = i;
        for (int j = 0; j <= m; j++) dp[0][j] = j;
        for (int i = 1; i <= n; i++) for (int j = 1; j <= m; j++) {
            int cost = Character.toLowerCase(source.charAt(i - 1)) == Character.toLowerCase(target.charAt(j - 1)) ? 0 : 1;
            dp[i][j] = Math.min(dp[i - 1][j] + 1, Math.min(dp[i][j - 1] + 1, dp[i - 1][j - 1] + cost));
        }
        int[] boundary = new int[n + 1];
        int i = n, j = m;
        boundary[n] = m;
        while (i > 0 || j > 0) {
            if (i > 0 && j > 0) {
                int cost = Character.toLowerCase(source.charAt(i - 1)) == Character.toLowerCase(target.charAt(j - 1)) ? 0 : 1;
                if (dp[i][j] == dp[i - 1][j - 1] + cost) {
                    boundary[--i] = --j;
                    continue;
                }
            }
            if (j > 0 && dp[i][j] == dp[i][j - 1] + 1) { j--; continue; }
            if (i > 0) boundary[--i] = j;
        }
        boundary[n] = m;
        for (i = 1; i <= n; i++) boundary[i] = Math.max(boundary[i], boundary[i - 1]);
        return boundary;
    }

    private static ArrayList<TLRPC.MessageEntity> remapEntities(ArrayList<TLRPC.MessageEntity> entities, int[] map, int n) {
        if (entities == null || entities.isEmpty()) return entities;
        for (int k = 0; k < entities.size(); k++) {
            TLRPC.MessageEntity e = entities.get(k);
            if (e == null) continue;
            int s = e.offset, en = e.offset + e.length;
            if (s < 0) s = 0; if (s > n) s = n;
            if (en < 0) en = 0; if (en > n) en = n;
            int ns = map[s], ne = map[en];
            e.offset = ns;
            e.length = Math.max(0, ne - ns);
        }
        return entities;
    }

    private static boolean isProtected(TLRPC.MessageEntity e) {
        return e instanceof TLRPC.TL_messageEntityUrl
                || e instanceof TLRPC.TL_messageEntityTextUrl
                || e instanceof TLRPC.TL_messageEntityMention
                || e instanceof TLRPC.TL_messageEntityMentionName
                || e instanceof TLRPC.TL_inputMessageEntityMentionName
                || e instanceof TLRPC.TL_messageEntityHashtag
                || e instanceof TLRPC.TL_messageEntityCashtag
                || e instanceof TLRPC.TL_messageEntityBotCommand
                || e instanceof TLRPC.TL_messageEntityEmail
                || e instanceof TLRPC.TL_messageEntityPhone
                || e instanceof TLRPC.TL_messageEntityCode
                || e instanceof TLRPC.TL_messageEntityPre
                || e instanceof TLRPC.TL_messageEntityBankCard
                || e instanceof TLRPC.TL_messageEntityCustomEmoji;
    }

    private static boolean isCyrillicLetter(char c) {
        return (c >= 0x0410 && c <= 0x044F)
                || c == 0x0401 || c == 0x0451
                || c == 'і' || c == 'І' || c == 'ѣ' || c == 'Ѣ'
                || c == 'ѳ' || c == 'Ѳ' || c == 'ѵ' || c == 'Ѵ';
    }

    private static String convertWord(String word) {
        int caseKind = caseKindOf(word);
        String lower = word.toLowerCase(Locale.ROOT);
        String override = COMMON_DICT.get(lower);
        String s;
        if (override != null) {
            s = override;
        } else {
            s = lower;
            s = applyYatRoots(s);
            s = applyYatInfinitive(s);
            s = applyFitaMorphemes(s);
            s = applyIDecimal(s);
            s = applyZPrefix(s);
            s = applyAdjGenitive(s);
            s = addFinalHardSign(s);
        }
        return applyCase(s, caseKind);
    }

    private static String applyYatRoots(String s) {
        for (int r = 0; r < YAT_ROOTS.length; r++) {
            if (s.contains(YAT_ROOTS[r][0])) s = s.replace(YAT_ROOTS[r][0], YAT_ROOTS[r][1]);
        }
        return s;
    }

    private static String applyYatInfinitive(String s) {
        if (s.endsWith("еться") && !s.endsWith("ереться")) return s.substring(0, s.length() - 5) + "ѣться";
        if (s.endsWith("еть") && !s.endsWith("ереть")) return s.substring(0, s.length() - 3) + "ѣть";
        return s;
    }

    private static String applyFitaMorphemes(String s) {
        for (int r = 0; r < FITA_MORPH.length; r++) {
            if (s.contains(FITA_MORPH[r][0])) s = s.replace(FITA_MORPH[r][0], FITA_MORPH[r][1]);
        }
        return s;
    }

    private static String applyIDecimal(String s) {
        int len = s.length();
        StringBuilder b = null;
        for (int i = 0; i < len; i++) {
            char c = s.charAt(i);
            if (c == 'и' && i + 1 < len && isITrigger(s.charAt(i + 1))) {
                if (b == null) b = new StringBuilder(s.substring(0, i));
                b.append('і');
            } else if (b != null) {
                b.append(c);
            }
        }
        return b == null ? s : b.toString();
    }

    private static boolean isITrigger(char c) { return c == 'й' || isVowel(c); }

    private static String applyZPrefix(String s) {
        if (s.startsWith("расс")) return "разс" + s.substring(4);
        if (s.startsWith("исс"))  return "изс" + s.substring(3);
        if (s.startsWith("восс")) return "возс" + s.substring(4);
        if (s.startsWith("нисс")) return "низс" + s.substring(4);
        if (s.startsWith("бес") && s.length() > 3 && isHardConsonantOrSoftCons(s.charAt(3)))
            return "без" + s.substring(3);
        if (s.startsWith("черес") && s.length() > 5 && isHardConsonantOrSoftCons(s.charAt(5)))
            return "через" + s.substring(5);
        if (s.startsWith("чрес") && s.length() > 4 && isHardConsonantOrSoftCons(s.charAt(4)))
            return "чрез" + s.substring(4);
        return s;
    }

    private static String applyAdjGenitive(String s) {
        if (ADJ_GEN_KEEP.contains(s)) return s;
        if (s.length() >= 5 && s.endsWith("ого")) return s.substring(0, s.length() - 3) + "аго";
        if (s.length() >= 5 && s.endsWith("его")) return s.substring(0, s.length() - 3) + "яго";
        return s;
    }

    private static String addFinalHardSign(String s) {
        if (s.isEmpty()) return s;
        return isFinalHardConsonant(s.charAt(s.length() - 1)) ? s + "ъ" : s;
    }

    private static boolean isSkippableAdjective(String lower) {
        return lower.endsWith("ом") || lower.endsWith("ём") || lower.endsWith("ем")
                || lower.endsWith("ых") || lower.endsWith("их")
                || PREP_SKIP_WORDS.contains(lower);
    }

    private static String applyPrepEnding(String conv, String lower) {
        if (conv.isEmpty()) return conv;
        char last = conv.charAt(conv.length() - 1);
        if (last != 'е' && last != 'Е') return conv;                 
        if (lower.length() < 2) return conv;
        if (isVowel(lower.charAt(lower.length() - 2))) return conv;  
        if (INDECL_E.contains(lower) || STAY_E.contains(lower)) return conv;
        return conv.substring(0, conv.length() - 1) + (last == 'Е' ? 'Ѣ' : 'ѣ');
    }

    private static boolean isVowel(char c) {
        switch (c) {
            case 'а': case 'е': case 'ё': case 'и': case 'о':
            case 'у': case 'ы': case 'э': case 'ю': case 'я':
            case 'і': case 'ѣ': case 'ѵ': return true;
            default: return false;
        }
    }

    private static boolean isFinalHardConsonant(char c) {
        switch (c) {
            case 'б': case 'в': case 'г': case 'д': case 'ж': case 'з':
            case 'к': case 'л': case 'м': case 'н': case 'п': case 'р':
            case 'с': case 'т': case 'ф': case 'х': case 'ц': case 'ч':
            case 'ш': case 'щ': case 'ѳ': return true;
            default: return false;
        }
    }

    private static boolean isHardConsonantOrSoftCons(char c) {
        
        return isFinalHardConsonant(c) || c == 'й';
    }

    private static int caseKindOf(String w) {
        boolean anyUpper = false, anyLower = false, firstUpper = false;
        for (int i = 0; i < w.length(); i++) {
            char c = w.charAt(i);
            boolean up = Character.isUpperCase(c), lo = Character.isLowerCase(c);
            if (i == 0) firstUpper = up;
            if (up) anyUpper = true;
            if (lo) anyLower = true;
        }
        if (anyUpper && !anyLower) return w.length() == 1 ? 2 : 1; 
        if (firstUpper && anyUpper && anyLower) {
            for (int i = 1; i < w.length(); i++) if (Character.isUpperCase(w.charAt(i))) return 3;
            return 2;
        }
        if (anyUpper) return 3;
        return 0;
    }

    private static String applyCase(String s, int kind) {
        switch (kind) {
            case 1: return s.toUpperCase();
            case 2: case 3:
                if (s.isEmpty()) return s;
                return Character.toUpperCase(s.charAt(0)) + s.substring(1);
            default: return s;
        }
    }

